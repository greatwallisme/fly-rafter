#!/usr/bin/env python3
"""Extract the headless `--help` text constant from the dsh cli-help doc.

The `fr headless` help output is brand-replaced dsh wording (headless spec,
2026-11-04 18b Q6 ruling): the fenced text block under the `` `dsh headless` ``
heading of docs/cli-help.md is extracted, the invocation spellings are mapped
to the fr CLI face ("dsh --profile headless" -> "fr headless", any residual
"dsh" -> "fr"), and the result is regenerated into
crates/fr-headless/src/help_text.rs. Run from the repository root:

    FR_DSH_SOURCE=<dsh checkout> python3 scripts/extract-headless-help.py
    FR_DSH_SOURCE=<dsh checkout> python3 scripts/extract-headless-help.py --check
"""

from __future__ import annotations

import difflib
import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_PATH = os.path.join(REPO_ROOT, "crates", "fr-headless", "src", "help_text.rs")

HEADER = """\
//! Generated `fr headless --help` text; do not edit.
//!
//! @generated by scripts/extract-headless-help.py from the deepseek-harness
//! cli-help doc (`FR_DSH_SOURCE`). DO NOT EDIT: rerun
//! `FR_DSH_SOURCE=<dsh checkout> python3 scripts/extract-headless-help.py`.
//! Brand mapping per the headless spec ruling: the invocation spellings map
//! to the fr CLI face ("dsh --profile headless" -> "fr headless", residual
//! "dsh" -> "fr"); every other character is verbatim.

// Rust guideline compliant {date}
"""


def brand_map(text: str) -> str:
    """Maps the dsh invocation spellings to the fr CLI face."""
    return text.replace("dsh --profile headless", "fr headless").replace("dsh", "fr")


def extract_help(source: str) -> str:
    """Extracts the fenced text block under the headless heading."""
    lines = source.splitlines()
    inside_section = False
    inside_fence = False
    captured: list[str] = []
    for line in lines:
        if not inside_section and line.strip() == "## `dsh headless`":
            inside_section = True
            continue
        if not inside_section:
            continue
        if not inside_fence and line.strip() == "```text":
            inside_fence = True
            continue
        if inside_fence and line.strip() == "```":
            break
        if inside_fence:
            captured.append(line)
    if not captured:
        print("error: headless help block not found in cli-help.md", file=sys.stderr)
        raise SystemExit(1)
    return brand_map("\n".join(captured))


def render(help_text: str) -> str:
    """Renders the Rust module: one raw string constant, blank-line exact."""
    body = help_text.replace("\\", "\\\\").replace('"', '\\"')
    literal_lines = ",\n".join(f'    "{line}\\n"' for line in body.splitlines())
    return (
        HEADER.format(date="2026-11-04")
        + "\n"
        + "/// The `fr headless --help` output, newline-terminated per line.\n"
        + "pub const HEADLESS_HELP: &str = concat!(\n"
        + literal_lines
        + ",\n);\n"
    )


def main() -> int:
    source_root = os.environ.get("FR_DSH_SOURCE")
    if not source_root:
        print(
            "extract-headless-help: set FR_DSH_SOURCE to the deepseek-harness "
            "checkout to read docs/cli-help.md from",
            file=sys.stderr,
        )
        return 1
    doc_path = os.path.join(source_root, "docs", "cli-help.md")
    with open(doc_path, encoding="utf-8") as handle:
        help_text = extract_help(handle.read())
    rendered = render(help_text)

    if "--check" in sys.argv[1:]:
        with open(OUT_PATH, encoding="utf-8") as handle:
            current = handle.read()
        if current == rendered:
            return 0
        for line in difflib.unified_diff(
            current.splitlines(), rendered.splitlines(), "current", "generated", lineterm=""
        ):
            print(line)
        print(
            "extract-headless-help: help_text.rs is stale; rerun the script "
            "without --check",
            file=sys.stderr,
        )
        return 1

    with open(OUT_PATH, "w", encoding="utf-8") as handle:
        handle.write(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
