HEADER = """\
//! Generated shell-tool catalog constants; do not edit.
//!
//! @generated by scripts/generate-tool-catalog.py from the deepseek-harness
//! docs/tool-catalog.md (FR_DSH_SOURCE). DO NOT EDIT: rerun
//! `FR_DSH_SOURCE=<dsh checkout> scripts/generate-tool-catalog.py`.
//! The managed-variable prefix alone is brand-mapped ($DSH_ -> $FR_,
//! the PRD 10 judgment); every other byte is catalog-verbatim.

#![allow(
    clippy::doc_markdown,
    reason = "generated provenance comments quote catalog paths verbatim"
)]"""


class ExtractError(Exception):
    """One catalog anchor failed to resolve against the sources."""


def raw_literal(text):
    """Renders one text as a raw Rust string literal.

    A raw string closes at the sequence `"` + hashes (backslashes are
    literal there), so the delimiter grows until the text can no longer
    close it.
    """
    hashes = ""
    while f'"{hashes}' in text:
        hashes += "#"
    return f'r{hashes}"{text}"{hashes}'


def read_catalog(source_root):
    with open(os.path.join(source_root, CATALOG), encoding="utf-8") as handle:
        return handle.read()


def extract_tool(text, tool):
    """Extracts one tool's description paragraph and parameters JSON."""
    anchor = re.search(rf"^### `{tool}`$", text, re.M)
    if anchor is None:
        raise ExtractError(f"catalog has no `### `{tool}`` section")
    body = text[anchor.end():]
    next_heading = re.search(r"^#{2,3} `", body[1:], re.M)
    if next_heading is not None:
        body = body[: 1 + next_heading.start()]
    fence = body.split("```json", 1)
    if len(fence) != 2:
        raise ExtractError(f"catalog section `{tool}` carries no json fence")
    description = fence[0].strip()
    json_text = fence[1].split("```", 1)[0].strip()
    try:
        parsed = json.loads(json_text)
    except json.JSONDecodeError as error:
        raise ExtractError(f"catalog section `{tool}` json fence: {error}") from error
    return description, json_text, parsed


def ts_unescape(segment):
    """Unescapes one TS single-quoted literal body (fail-closed)."""
    out = []
    index = 0
    while index < len(segment):
        char = segment[index]
        if char != "\\":
            out.append(char)
            index += 1
            continue
        index += 1
        if index >= len(segment):
            raise ExtractError("dangling backslash in a section text literal")
        escape = segment[index]
        mapped = {"'": "'", "\\": "\\", "n": "\n", "t": "\t"}.get(escape)
        if mapped is None:
            raise ExtractError(f"unsupported escape \\{escape} in a section text literal")
        out.append(mapped)
        index += 1
    return "".join(out)


def extract_section_text(source, tool):
    """Extracts one tool's prompt-section text (the dsh
    `ctx.systemPrompt.section` call; a multi-segment `'a' + 'b'`
    concatenation joins into one text)."""
    anchor = source.find(f"name: 'tool:{tool}'")
    if anchor < 0:
        raise ExtractError(f"tool source carries no section for `tool:{tool}`")
    call_end = source.find("})", anchor)
    if call_end < 0:
        raise ExtractError(f"the `tool:{tool}` section call never closes")
    body = source[anchor:call_end]
    marker = body.find("text:")
    if marker < 0:
        raise ExtractError(f"the `tool:{tool}` section call carries no text")
    expression = body[marker + len("text:"):]
    segments = re.findall(r"'((?:[^'\\]|\\.)*)'", expression)
    if not segments:
        raise ExtractError(f"the `tool:{tool}` section text parses no literals")
    return "".join(ts_unescape(segment) for segment in segments)


def extract_section_text_segments(source, tool):
    """Extracts one tool's prompt-section text as its non-empty literal
    segments (the dsh section texts that compose conditionally: the
    `ctx.tools.get(...)` probes strip out first, then the remaining
    string literals join in source order, empty ternary arms dropped)."""
    anchor = source.find(f"name: 'tool:{tool}'")
    if anchor < 0:
        raise ExtractError(f"tool source carries no section for `tool:{tool}`")
    call_end = source.find("\n  })", anchor)
    if call_end < 0:
        close = source.find("})", anchor)
        if close < 0:
            raise ExtractError(f"the `tool:{tool}` section call never closes")
        call_end = close
    body = source[anchor:call_end]
    marker = body.find("text:")
    if marker < 0:
        raise ExtractError(f"the `tool:{tool}` section call carries no text")
    expression = body[marker + len("text:"):]
    stripped = re.sub(r"ctx\.tools\.get\('[^']+', scope\)", "", expression)
    literals = re.findall(r"'((?:[^'\\]|\\.)*)'", stripped)
    segments = [ts_unescape(segment) for segment in literals]
    kept = [segment for segment in segments if segment]
    if not kept:
        raise ExtractError(f"the `tool:{tool}` section text parses no literals")
    return kept


def extract_overcap_variants(source):
    """Extracts the glob description's over-cap behavior phrases (the dsh
    `overCapDescription` ternary): the sampled phrase and the
    modification-time-head phrase, in ternary order."""
    anchor = source.find("const overCapDescription = caps.sampleOverCapGlobResults")
    if anchor < 0:
        raise ExtractError("glob source carries no overCapDescription ternary")
    line_end = source.find("\n", anchor)
    line = source[anchor:line_end if line_end > 0 else len(source)]
    literals = re.findall(r"'((?:[^'\\]|\\.)*)'", line)
    if len(literals) != 2:
        raise ExtractError(
            f"the overCapDescription ternary parses {len(literals)} literals, expected 2"
        )
    return literals[0], literals[1]


def brand_map(text):
    """The FR_ prefix ruling: the managed-variable prefix alone maps."""
    return text.replace("$env:DSH_", "$env:FR_").replace("DSH_", "FR_")


def parameter_text(parsed, key):
    """One property's catalog description text."""
    properties = parsed.get("properties", {})
    if key not in properties:
        raise ExtractError(f"catalog parameters carry no `{key}` property")
    description = properties[key].get("description")
    if not isinstance(description, str):
        raise ExtractError(f"catalog property `{key}` carries no description text")
    return description


def emit():
    source_root = os.environ.get("FR_DSH_SOURCE")
    if not source_root:
        print(
            "generate-tool-catalog: set FR_DSH_SOURCE to the deepseek-harness "
            "checkout (the catalog constants extract against the sources)",
            file=sys.stderr,
        )
        return 1
    catalog = read_catalog(source_root)
    blocks = [HEADER]
    extracted = {}
    for tool, (stem, keys, section_kind) in TOOLS.items():
        description, _, parsed = extract_tool(catalog, tool)
        description = brand_map(description)
        parameters = brand_map(json.dumps(parsed, indent=2, ensure_ascii=False))
        extracted[tool] = (description, parameters, parsed)
        blocks.append(f"\n/// The `{tool}` tool description (catalog-verbatim).\n")
        blocks.append(f"pub const {stem}_DESCRIPTION: &str = {raw_literal(description)};\n")
        blocks.append(
            f"\n/// The `{tool}` parameter table (the json block, verbatim).\n"
        )
        blocks.append(
            f"pub const {stem}_PARAMETERS_JSON: &str = {raw_literal(parameters)};\n"
        )
        if section_kind != "none":
            source_root_tool = os.path.join(source_root, TOOL_SOURCES[tool])
            with open(source_root_tool, encoding="utf-8") as handle:
                source = handle.read()
            if section_kind == "plain":
                section_text = brand_map(extract_section_text(source, tool))
                blocks.append(
                    f"\n/// The `tool:{tool}` prompt-section text (the dsh"
                    f" `ctx.systemPrompt.section` call, source-verbatim).\n"
                )
                blocks.append(
                    f"pub const {stem}_SECTION_TEXT: &str = {raw_literal(section_text)};\n"
                )
            else:
                segments = [brand_map(s) for s in extract_section_text_segments(source, tool)]
                if len(segments) == 1:
                    blocks.append(
                        f"\n/// The `tool:{tool}` prompt-section text (the dsh"
                        f" `ctx.systemPrompt.section` call, source-verbatim).\n"
                    )
                    blocks.append(
                        f"pub const {stem}_SECTION_TEXT: &str = {raw_literal(segments[0])};\n"
                    )
                else:
                    rendered = ", ".join(raw_literal(segment) for segment in segments)
                    blocks.append(
                        f"\n/// The `tool:{tool}` prompt-section text segments (the dsh"
                        f" `ctx.systemPrompt.section` call, source-verbatim; the consumer"
                        f" composes them with the source's conditional rule).\n"
                    )
                    blocks.append(
                        f"pub const {stem}_SECTION_TEXTS: [&str; {len(segments)}] = [{rendered}];\n"
                    )
        if tool == "glob":
            source_root_tool = os.path.join(source_root, TOOL_SOURCES["glob"])
            with open(source_root_tool, encoding="utf-8") as handle:
                source = handle.read()
            sampled, head = extract_overcap_variants(source)
            blocks.append(
                "\n/// The sampled over-cap phrase of the `glob` description (the dsh"
                " `overCapDescription` ternary's true arm, source-verbatim; the composed"
                " registration swaps by the baked sampling switch).\n"
            )
            blocks.append(
                f"pub const GLOB_OVERCAP_SAMPLED_TEXT: &str = {raw_literal(sampled)};\n"
            )
            blocks.append(
                "\n/// The head over-cap phrase of the `glob` description (the dsh"
                " `overCapDescription` ternary's false arm, source-verbatim).\n"
            )
            blocks.append(
                f"pub const GLOB_OVERCAP_HEAD_TEXT: &str = {raw_literal(head)};\n"
            )
        for key, suffix in keys:
            text = brand_map(parameter_text(parsed, key))
            blocks.append(
                f"\n/// The `{tool}` `{key}` parameter description (catalog-verbatim).\n"
            )
            blocks.append(
                f"pub const {stem}_{suffix}: &str = {raw_literal(text)};\n"
            )
    generated = "".join(blocks)
    return write_or_check(rustfmt(generated, ".rs"))


def write_or_check(canonical):
    """Writes the artifact, or diffs it under --check."""
    if "--check" in sys.argv[1:]:
        with open(OUT, encoding="utf-8") as handle:
            current = handle.read()
        if current != canonical:
            diff = difflib.unified_diff(
                current.splitlines(),
                canonical.splitlines(),
                fromfile="catalog_gen.rs (on disk)",
                tofile="catalog_gen.rs (regenerated)",
                lineterm="",
            )
            print("\n".join(diff), file=sys.stderr)
            print(
                "generate-tool-catalog --check reported drift: rerun "
                "scripts/generate-tool-catalog.py",
                file=sys.stderr,
            )
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(canonical)
    return 0


def rustfmt(text, suffix):
    """Normalizes one generated file through rustfmt.

    The on-disk artifact must be stable under `cargo fmt`, so the
    generator's canonical output IS the rustfmt-formatted text.
    """
    with tempfile.NamedTemporaryFile("w", suffix=suffix, delete=False, encoding="utf-8") as handle:
        handle.write(text)
        name = handle.name
    try:
        subprocess.run(
            ["rustfmt", "--edition", "2024", name],
            check=True,
            capture_output=True,
        )
        with open(name, encoding="utf-8") as handle:
            return handle.read()
    finally:
        os.unlink(name)


if __name__ == "__main__":
    sys.exit(emit())
